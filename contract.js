function printContract(data) {
  const html = buildContractHtml(data);
  let printWindow = null;
  try {
    printWindow = window.open('', '_blank', 'width=900,height=1200');
  } catch (error) {
    printWindow = null;
  }

  if (printWindow && printWindow.document) {
    try {
      printWindow.document.open();
      printWindow.document.write(html);
      printWindow.document.close();
      printWindow.focus();
      const launch = () => {
        try { printWindow.print(); } catch (error) { console.warn('Печать договора недоступна:', error); }
      };
      const images = Array.from(printWindow.document.images || []);
      const pending = images.filter((image) => !image.complete);
      if (!pending.length) {
        window.setTimeout(launch, 400);
      } else {
        let remaining = pending.length;
        const done = () => {
          remaining -= 1;
          if (remaining <= 0) window.setTimeout(launch, 300);
        };
        pending.forEach((image) => {
          image.addEventListener('load', done, { once: true });
          image.addEventListener('error', done, { once: true });
        });
        window.setTimeout(launch, 2500);
      }
      return;
    } catch (error) {
      console.warn('Не удалось открыть окно печати договора:', error);
    }
  }

  try {
    const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const fallback = window.open(url, '_blank');
    if (!fallback) {
      URL.revokeObjectURL(url);
      alert('Не удалось открыть договор. Разрешите всплывающие окна для этого сайта.');
    } else {
      setTimeout(() => URL.revokeObjectURL(url), 60000);
    }
  } catch (error) {
    console.error('Резервное открытие договора не удалось:', error);
    alert('Не удалось открыть договор.');
  }
}

