function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, (ch) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  }[ch]));
}

function plural(n, one, few, many) {
  const abs = Math.abs(Number(n));
  const tail = abs % 100;
  if (tail >= 11 && tail <= 14) return many;
  const last = abs % 10;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

function triadsToWords(value, feminine) {
  const units = feminine
    ? ['', 'одна', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять']
    : ['', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];
  const teens = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать'];
  const tens = ['', 'десять', 'двадцать', 'тридцать', 'сорок', 'пятьдесят', 'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто'];
  const hundreds = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот', 'шестьсот', 'семьсот', 'восемьсот', 'девятьсот'];
  const words = [];
  const h = Math.floor(value / 100);
  const t = Math.floor((value % 100) / 10);
  const u = value % 10;
  if (h) words.push(hundreds[h]);
  if (t === 1) words.push(teens[u]);
  else {
    if (t) words.push(tens[t]);
    if (u) words.push(units[u]);
  }
  return words;
}

function numberToWords(value) {
  let n = Math.max(0, Math.floor(Number(value) || 0));
  if (!n) return 'ноль';
  const groups = [];
  while (n > 0) {
    groups.push(n % 1000);
    n = Math.floor(n / 1000);
  }
  const scales = [
    { one: '', few: '', many: '', feminine: false },
    { one: 'тысяча', few: 'тысячи', many: 'тысяч', feminine: true },
    { one: 'миллион', few: 'миллиона', many: 'миллионов', feminine: false },
    { one: 'миллиард', few: 'миллиарда', many: 'миллиардов', feminine: false }
  ];
  const words = [];
  for (let i = groups.length - 1; i >= 0; i--) {
    const group = groups[i];
    if (!group) continue;
    const scale = scales[i] || scales[scales.length - 1];
    words.push(...triadsToWords(group, scale.feminine));
    if (i > 0) words.push(plural(group, scale.one, scale.few, scale.many));
  }
  return words.filter(Boolean).join(' ');
}

function dateInWords(date) {
  const d = date instanceof Date && Number.isFinite(date.getTime()) ? date : new Date();
  return d.getDate() + ' ' + MONTHS[d.getMonth()] + ' ' + d.getFullYear() + ' г.';
}

function amountParts(total) {
  const amount = Math.round((Number(total) || 0) * 100) / 100;
  let rubles = Math.floor(amount);
  let kopecks = Math.round((amount - rubles) * 100);
  if (kopecks >= 100) {
    rubles += 1;
    kopecks = 0;
  }
  return {
    rubles,
    kopecks,
    rublesText: new Intl.NumberFormat('ru-RU').format(rubles),
    kopecksText: String(kopecks).padStart(2, '0'),
    words: numberToWords(rubles),
    rubleWord: plural(rubles, 'рубль', 'рубля', 'рублей'),
    kopeckWord: plural(kopecks, 'копейка', 'копейки', 'копеек')
  };
}

function clauseHtml(text) {
  const trimmed = String(text || '').trim();
  if (!trimmed) return '';
  if (/^\d+\.\s/.test(trimmed)) return '<h2>' + esc(trimmed) + '</h2>';
  return '<p>' + esc(trimmed) + '</p>';
}

