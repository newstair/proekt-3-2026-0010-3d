function printContract(data) {
  const html = buildContractHtml(data);
  let printWindow = null;
  try {
    printWindow = window.open('', '_blank', 'width=900,height=1200');
  } catch (error) {
    printWindow = null;
  }

  if (printWindow && printWindow.document) {
    try {
      printWindow.document.open();
      printWindow.document.write(html);
      printWindow.document.close();
      printWindow.focus();
      return;
    } catch (error) {
      console.warn('Не удалось открыть окно договора:', error);
    }
  }

  try {
    const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const fallback = window.open(url, '_blank');
    if (!fallback) {
      URL.revokeObjectURL(url);
      alert('Не удалось открыть договор. Разрешите всплывающие окна для этого сайта.');
    } else {
      setTimeout(() => URL.revokeObjectURL(url), 60000);
    }
  } catch (error) {
    console.error('Резервное открытие договора не удалось:', error);
    alert('Не удалось открыть договор.');
  }
}

